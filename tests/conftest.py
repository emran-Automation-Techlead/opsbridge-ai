import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
_SPEC_TO_TESTS: dict[str, list[str]] = {}
_RESULTS: dict[str, str] = {}


@pytest.fixture(autouse=True)
def isolated_runs(tmp_path, monkeypatch):
    """Every test writes traces/audit/tickets to its own temp dir."""
    monkeypatch.setenv("OPSBRIDGE_RUNS", str(tmp_path / "runs"))
    monkeypatch.delenv("OPSBRIDGE_LLM", raising=False)
    monkeypatch.delenv("OPSBRIDGE_STORE", raising=False)
    from opsbridge import store
    store.reset_cache()
    yield
    store.reset_cache()


def pytest_collection_modifyitems(config, items):
    for item in items:
        for m in item.iter_markers("spec"):
            _SPEC_TO_TESTS.setdefault(m.args[0], []).append(item.nodeid)


def pytest_runtest_logreport(report):
    if report.when == "call":
        _RESULTS[report.nodeid] = report.outcome


def spec_ids() -> list[str]:
    return re.findall(r"^## (SPEC-\d{3})", (ROOT / "specs" / "SPECS.md").read_text(encoding="utf-8"), re.MULTILINE)


def pytest_sessionfinish(session, exitstatus):
    if not _SPEC_TO_TESTS:
        return
    rows = ["# Traceability: spec -> tests (generated by the test run)", "", "| Spec | Tests | Passed | Failed |", "|---|---|---|---|"]
    for sid in spec_ids():
        tests = _SPEC_TO_TESTS.get(sid, [])
        ok = sum(1 for t in tests if _RESULTS.get(t) == "passed")
        bad = sum(1 for t in tests if _RESULTS.get(t) == "failed")
        rows.append(f"| {sid} | {len(tests)} | {ok} | {bad} |")
    (ROOT / "docs" / "TRACEABILITY.md").write_text("\n".join(rows) + "\n", encoding="utf-8")


@pytest.fixture(scope="session")
def spec_map():
    return _SPEC_TO_TESTS
